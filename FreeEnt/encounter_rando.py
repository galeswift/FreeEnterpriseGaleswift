def apply(env):
    doors_to_disable = []
    behemoths_to_disable = []

    env.add_file('scripts/encounter_reduction.f4c')
    env.add_file('scripts/encounter_average_level.f4c')

    if not env.options.flags.has('encounter_keep_doors'):
        if env.options.flags.has('encounter_reduction'):
            # only disable half the trapdoors
            doors_to_disable = env.rnd.sample(TRAPDOORS, math.ceil(len(TRAPDOORS) * 0.6))
        elif env.options.flags.has('encounter_off'):
            # disable all trapdoors
            doors_to_disable = TRAPDOORS

        for d in doors_to_disable:
            env.add_substitution(f'trapdoor {d}', 'set #Temp')
    else:
        for d in TRAPDOORS:
            env.add_substitution(f'trapdoor {d}', 'clear #Temp')

    if not env.options.flags.has('encounter_keep_behemoths'):
        if env.options.flags.has('encounter_reduction'):
            # each behemoth has a 50/50 chance of being disabled
            behemoths_to_disable = [i for i in BEHEMOTHS if env.rnd.random() < 0.5]
        elif env.options.flags.has('encounter_off'):
            # disable all behemoths
            behemoths_to_disable = BEHEMOTHS

        if behemoths_to_disable:
            env.add_file('scripts/bahamut_no_behemoths.f4c')
            for b in BEHEMOTHS:
                if b not in behemoths_to_disable:
                    env.add_substitution(f'{b} disable', '')
    else:
        env.add_substitution('behemoth use toggle', '')

    if env.options.flags.has_any('encounter_toggle', 'encounter_norepeats'):
        env.add_file('scripts/encounter_toggle.f4c')
        env.add_toggle('toggled_encounters')
        if env.options.flags.has('encounter_norepeats'):
            env.add_file('scripts/encounter_norepeats.f4c')
    
    if env.options.flags.has('encounter_dangerous') and env.options.flags.has_any('encounter_toggle', 'encounter_norepeats', 'encounter_off'):
        env.add_file('scripts/encounter_dangerous.f4c')
    else:
        env.add_substitution('encounter dangerous on', '')

    if not env.options.flags.has_any('encounter_toggle', 'encounter_norepeats', 'encounter_off'):
        env.add_substitution('encounter default off', '')

    if not env.options.flags.has('encounter_reduction'):
        env.add_substitution('encounter reduction', '')

    if env.options.flags.has('encounter_cant_run'):
        env.add_file('scripts/cant_run.f4c')
    else:
        run_spoils_flag = env.options.flags.get_suffix('Erunspoils')
        if run_spoils_flag:
            env.add_file('scripts/encounter_run_spoils.f4c')
            run_spoils_flag = int(run_spoils_flag)
            if run_spoils_flag in [25, 50]:
                loop_num = 50 // run_spoils_flag
                env.add_substitution('run penalty loop', f'#$00{loop_num:02X}')
                env.add_toggle('run_experience_penalty')
                env.add_toggle('run_gp_penalty')

    if env.options.flags.has('no_gp_for_random_encounters'):
        env.add_file('scripts/encounter_no_gp.f4c')
        env.add_toggle('no_gp_from_encounters')

    if env.options.flags.has('encounter_no_dmachin'):
        env.add_file('scripts/encounter_no_dmachin.f4c')
    if env.options.flags.has('encounter_no_macgiant'):
        env.add_file('scripts/encounter_no_macgiant.f4c')

    table_flag = env.options.flags.get_suffix('Etable:')
    if not table_flag:
        return
    
    if table_flag.startswith('shuffle'):
        shuffle_param = int(table_flag[-1])
        enc_script = '\n'
        spoilers = []
        for group_id in ENCOUNTERS_BY_GROUP:
            formation_indices = [i for i in range(shuffle_param)]
            env.rnd.shuffle(formation_indices)
            formation_indices += ([7] if shuffle_param == 7 else [])
            enc_script += f'patch(${(0x0EC796 + 8*group_id):06X} bus) {{' + ' '.join([f'{ENCOUNTERS_BY_GROUP[group_id][0][i]:02X}' for i in formation_indices]) + ' }\n'
            spoilers.append( (databases.get_encounter_group_names(group_id)[0], 
                              ', '.join([f'{formation_indices[i] + 1}' for i in range(8)]) ))
        env.add_script(enc_script)
        # spoilers.sort(key=(lambda t: t[0]))
        env.spoilers.add_table("ENCOUNTER GROUPS\nFormations in order of increasing rarity", spoilers, public=env.options.flags.has_any('-spoil:all', '-spoil:encounters'), ditto_depth=1) 

    elif table_flag.startswith('relocated'):
        zones = {}
        zone_groups = ([['overworld'], ['underworld'], ['hookgiant'], ['moon']] if table_flag.endswith('ish') else [['overworld', 'hookgiant'], ['underworld', 'moon']])
        for zone_group in zone_groups:
            zones.update({' '.join(zone_group) : [group_id for group_id in ENCOUNTERS_BY_GROUP if ENCOUNTERS_BY_GROUP[group_id][1] in zone_group]})
        enc_script = '\n'
        spoilers = []
        for zone in zones:
            group_ids_list = zones[zone].copy()
            env.rnd.shuffle(group_ids_list)
            for i in range(len(zones[zone])): 
                enc_script += f'patch(${(0x0EC796 + 8*(zones[zone][i])):06X} bus) {{' + ' '.join([f'{byte:02X}' for byte in ENCOUNTERS_BY_GROUP[group_ids_list[i]][0]]) + ' }\n'
                spoilers.append( (databases.get_encounter_group_names(zones[zone][i])[0], databases.get_encounter_group_names(group_ids_list[i])[0]) )
        env.add_script(enc_script)
        # spoilers.sort(key=(lambda t: t[0]))
        env.spoilers.add_table("ENCOUNTER GROUPS", spoilers, public=env.options.flags.has_any('-spoil:all', '-spoil:encounters'), ditto_depth=1) 

    elif table_flag.startswith('wild'):
        zones = {}
        zone_groups = ([['overworld'], ['underworld'], ['hookgiant'], ['moon']] if table_flag.endswith('ish') else [['overworld', 'hookgiant'], ['underworld', 'moon']])
        for zone_group in zone_groups:
            group_ids_list = [group_id for group_id in ENCOUNTERS_BY_GROUP if ENCOUNTERS_BY_GROUP[group_id][1] in zone_group]
            encounters_list = []
            for group_id in group_ids_list:
                encounters_list.extend(ENCOUNTERS_BY_GROUP[group_id][0])
            zones.update({' '.join(zone_group) : (group_ids_list,encounters_list)})
        enc_script = '\n'
        spoilers = []
        for zone in zones:
            encounters_list = zones[zone][1]
            env.rnd.shuffle(encounters_list)
            for i in range(len(zones[zone][0])):
                group_id = zones[zone][0][i]
                formations = encounters_list[i:i+8]
                enc_script += f'patch(${(0x0EC796 + 8*group_id):06X} bus) {{' + ' '.join([f'{byte:02X}' for byte in formations]) + ' }\n'
                spoilers.append( (databases.get_encounter_group_names(group_id)[0], 
                                  ', '.join([('1' if ENCOUNTERS_BY_GROUP[group_id][1] in ['underworld','moon'] else ' ') + f'{byte:02X}' for byte in formations])) )
        env.add_script(enc_script)
        # spoilers.sort(key=lambda t : t[0])
        env.spoilers.add_table("ENCOUNTER GROUPS\nValues are formation IDs", spoilers, public=env.options.flags.has_any('-spoil:all', '-spoil:encounters'), ditto_depth=1) 

    elif table_flag == 'chaos':
        zones = [['overworld', 'hookgiant'], ['underworld', 'moon']]
        enc_script = '\n'
        spoilers = []
        for zone_group in zones:
            encounters_set = set()
            group_ids_list = [group_id for group_id in ENCOUNTERS_BY_GROUP if ENCOUNTERS_BY_GROUP[group_id][1] in zone_group]
            for group_id in group_ids_list:
                encounters_set = encounters_set.union(set(ENCOUNTERS_BY_GROUP[group_id][0]))
            sorted_encounters = sorted(encounters_set)
            for group_id in group_ids_list:
                new_encounters = []
                for i in range(8):
                    new_encounters.append(env.rnd.sample(sorted_encounters, 1)[0])
                enc_script += f'patch(${(0x0EC796 + 8*group_id):06X} bus) {{' + ' '.join([f'{byte:02X}' for byte in new_encounters]) + ' }\n'
                spoilers.append( (databases.get_encounter_group_names(group_id)[0], 
                                  ', '.join([('1' if ENCOUNTERS_BY_GROUP[group_id][1] in ['underworld','moon'] else ' ') + f'{byte:02X}' for byte in new_encounters])) )
        env.add_script(enc_script)
        # spoilers.sort(key=lambda t : t[0])
        env.spoilers.add_table("ENCOUNTER GROUPS\nValues are formation IDs", spoilers, public=env.options.flags.has_any('-spoil:all', '-spoil:encounters'), ditto_depth=1) 

    elif table_flag == 'uniquelygood':
        enc_script = '\n'
        spoilers = []
        for group_id in ENCOUNTERS_BY_GROUP:
            enc_script += f'patch(${(0x0EC796 + 8*group_id):06X} bus) {{' + ' '.join([f'{ENCOUNTERS_BY_GROUP[group_id][2]:02X}']*8) + ' }\n'
            spoilers.append(databases.get_encounter_group_names(group_id))
        env.add_script(enc_script)
        env.spoilers.add_table("ENCOUNTER GROUPS", spoilers, public=env.options.flags.has_any('-spoil:all', '-spoil:encounters'), ditto_depth=1)